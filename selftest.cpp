static int gFails = 0;

static uint32_t bitsOf(float f) { uint32_t u; memcpy(&u, &f, 4); return u; }
static float fOf(uint32_t u) { float f; memcpy(&f, &u, 4); return f; }

// distance in representable floats, huge when either side is not a number
static long long ulps(float a, float b) {
  if (a != a || b != b) return 1000000000LL;
  int32_t x = (int32_t)bitsOf(a), y = (int32_t)bitsOf(b);
  if (x < 0) x = INT32_MIN - x;
  if (y < 0) y = INT32_MIN - y;
  long long d = (long long)x - y;
  return d < 0 ? -d : d;
}

static void report(const char *name, int n, int bad, long long worst) {
  printf("%s %s, %d cases, worst %lld\n", bad ? "FAIL" : "PASS", name, n, worst);
  if (bad) gFails++;
}

static void testCurve() {
  int n = (int)(sizeof curveRows / sizeof curveRows[0]), bad = 0;
  long long worst = 0;
  for (int i = 0; i < n; i++) {
    float got = curveFactor(curveRows[i].curve, fOf(curveRows[i].speed));
    long long d = ulps(got, fOf(curveRows[i].want));
    if (d > worst) worst = d;
    if (d != 0) { bad++; printf("  curve %d speed %g got %.9g want %.9g\n", curveRows[i].curve, fOf(curveRows[i].speed), got, fOf(curveRows[i].want)); }
  }
  report("curve factor, exact", n, bad, worst);
}

static void testBlend() {
  int n = (int)(sizeof blendRows / sizeof blendRows[0]), bad = 0;
  long long worst = 0;
  for (int i = 0; i < n; i++) {
    const BlendRow &r = blendRows[i];
    float got = blendGain(fOf(r.a), fOf(r.b), fOf(r.w));
    long long d = ulps(got, fOf(r.want));
    if (d > worst) worst = d;
    if (d > 2) { bad++; printf("  blend %g %g %g got %.9g want %.9g\n", fOf(r.a), fOf(r.b), fOf(r.w), got, fOf(r.want)); }
  }
  report("sensitivity blend, two ulp", n, bad, worst);
}

static void testGain() {
  int n = (int)(sizeof gainRows / sizeof gainRows[0]), bad = 0;
  long long worst = 0;
  for (int i = 0; i < n; i++) {
    const GainRow &r = gainRows[i];
    gLongSide = fOf(r.wl);
    float got = gainOf(fOf(r.kh), fOf(r.kv), r.curve, fOf(r.dh), fOf(r.dv));
    long long d = ulps(got, fOf(r.want));
    if (d > worst) worst = d;
    if (d > 2) { bad++; printf("  gain row %d got %.9g want %.9g\n", i, got, fOf(r.want)); }
  }
  report("frame factor, two ulp", n, bad, worst);
}

// the reference rounds a scaled position as floor of the value plus one half. the last rows are the
// saturation of flick, not part of the reference, they keep a runaway value from overflowing.
static void testRound() {
  static const struct { float v; int want; } rows[] = {
    {0.0f, 0}, {0.49f, 0}, {0.5f, 1}, {1.5f, 2}, {2.5f, 3}, {-0.49f, 0}, {-0.5f, 0}, {-1.5f, -1}, {-2.5f, -2}, {-2.51f, -3},
    {1079.4f, 1079}, {1079.5f, 1080}, {3.0e9f, 2000000000}, {-3.0e9f, -2000000000}, {__builtin_nanf(""), 0}};
  int n = (int)(sizeof rows / sizeof rows[0]), bad = 0;
  for (int i = 0; i < n; i++) {
    int got = roundInt(rows[i].v);
    if (got != rows[i].want) { bad++; printf("  round %.9g got %d want %d\n", rows[i].v, got, rows[i].want); }
  }
  report("position rounding, exact", n, bad, 0);
}

static void testEuro() {
  int n = (int)(sizeof euroRows / sizeof euroRows[0]), bad = 0, pts = 0;
  for (int i = 0; i < n; i++) {
    const EuroRow &r = euroRows[i];
    Config c;
    c.minCut = fOf(r.minCut);
    c.beta = fOf(r.beta);
    gInvShort = 1.0f;
    Axis a;
    memset(&a, 0, sizeof a);
    for (int k = 0; k < r.n; k++) {
      float got = euroStep(a, fOf(r.p[k].x), r.p[k].ms, c);
      pts++;
      if (bitsOf(got) != r.p[k].want) { bad++; printf("  euro row %d step %d got %.9g want %.9g\n", i, k, got, fOf(r.p[k].want)); }
    }
  }
  report("one euro filter, exact", pts, bad, 0);
}

// sends one scenario through pump and compares every event that comes out
static int runScen(const Scen &s) {
  memset(gAbs, 0, sizeof gAbs);
  gAbs[ABS_MT_POSITION_X].maximum = s.xmax;
  gAbs[ABS_MT_POSITION_Y].maximum = s.ymax;
  gAbs[ABS_MT_SLOT].maximum = 9;
  gVertX = s.xmax < s.ymax;
  gLongSide = (float)(s.xmax > s.ymax ? s.xmax : s.ymax);
  gInvShort = s.smooth ? 1.0f : 1.0f / (float)(s.xmax < s.ymax ? s.xmax : s.ymax);
  Config c;
  c.sensH = s.sensH;
  c.sensV = s.sensV;
  c.curve = s.curve;
  c.zone = s.zone;
  c.orient = s.orient;
  c.smooth = s.smooth;
  if (s.smooth) { c.minCut = s.minCut; c.beta = s.beta; }
  memset(gSlots, 0, sizeof gSlots);
  gCurSlot = 0;
  gDown = 0;
  gDirty = 0;
  int in[2], out[2];
  if (pipe(in) || pipe(out)) { printf("FAIL pipe\n"); return 1; }
  fcntl(in[0], F_SETFL, O_NONBLOCK);
  fcntl(out[0], F_SETFL, O_NONBLOCK);
  gSource = in[0];
  gUinput = out[1];
  static input_event buf[200], got[200];
  int bad = 0, moved = 0, total = 0, first = 0, worst = 0;
  for (int b = 0; b < s.nb; b++) {
    int last = s.end[b], n = last - first;
    memset(buf, 0, sizeof buf);
    for (int i = 0; i < n; i++) {
      const Ev &e = s.ev[first + i];
      buf[i].type = (uint16_t)e.type;
      buf[i].code = (uint16_t)e.code;
      buf[i].value = e.value;
      buf[i].time.tv_sec = e.ms / 1000;
      buf[i].time.tv_usec = (e.ms % 1000) * 1000;
    }
    if (!writeAll(in[1], buf, (size_t)n * sizeof(input_event)) || pump(c) != 1) { bad++; first = last; continue; }
    ssize_t r = read(out[0], got, sizeof got);
    if (r != (ssize_t)((size_t)n * sizeof(input_event))) { bad++; first = last; continue; }
    for (int i = 0; i < n; i++) {
      const Ev &e = s.ev[first + i];
      int want = s.want[first + i], diff = got[i].value - want;
      bool pos = e.type == EV_ABS && (e.code == ABS_MT_POSITION_X || e.code == ABS_MT_POSITION_Y);
      total++;
      if (got[i].type != e.type || got[i].code != e.code) bad++;
      else if (pos) {
        if (diff < 0) diff = -diff;
        if (diff > worst) worst = diff;
        if (diff > 1) bad++;
        if (got[i].value != e.value) moved++;
      } else if (got[i].value != want) bad++;
    }
    first = last;
  }
  close(in[0]); close(in[1]); close(out[0]); close(out[1]);
  gSource = gUinput = -1;
  printf("%s scenario %s, %d events, %d positions changed, worst %d raw\n", bad ? "FAIL" : "PASS", s.name, total, moved, worst);
  return bad ? 1 : 0;
}

// a syn_dropped must forward what came before it, forget the open frame and lift the fingers
static int testDrop() {
  memset(gAbs, 0, sizeof gAbs);
  gAbs[ABS_MT_POSITION_X].maximum = 1079;
  gAbs[ABS_MT_POSITION_Y].maximum = 2399;
  gAbs[ABS_MT_SLOT].maximum = 9;
  gVertX = true;
  gLongSide = 2399.0f;
  gInvShort = 1.0f / 1079.0f;
  Config c;
  c.sensH = 2.0f;
  c.sensV = 3.0f;
  c.curve = curveAccel;
  memset(gSlots, 0, sizeof gSlots);
  gCurSlot = 0;
  gDown = 0;
  gDirty = 0;
  int in[2], out[2];
  if (pipe(in) || pipe(out)) { printf("FAIL pipe\n"); return 1; }
  fcntl(in[0], F_SETFL, O_NONBLOCK);
  fcntl(out[0], F_SETFL, O_NONBLOCK);
  gSource = in[0];
  gUinput = out[1];
  static const Ev one[] = {{EV_ABS, ABS_MT_SLOT, 2, 5000}, {EV_ABS, ABS_MT_TRACKING_ID, 7, 5000}, {EV_ABS, ABS_MT_POSITION_X, 500, 5000},
                           {EV_ABS, ABS_MT_POSITION_Y, 1200, 5000}, {EV_SYN, SYN_REPORT, 0, 5000}, {EV_ABS, ABS_MT_POSITION_X, 520, 5008},
                           {EV_ABS, ABS_MT_POSITION_Y, 1230, 5008}, {EV_SYN, SYN_REPORT, 0, 5008}};
  static const Ev two[] = {{EV_ABS, ABS_MT_POSITION_X, 540, 5016}, {EV_SYN, SYN_DROPPED, 0, 5016}, {EV_ABS, ABS_MT_POSITION_X, 999, 5016},
                           {EV_SYN, SYN_REPORT, 0, 5016}};
  static input_event buf[8], got[8];
  int bad = 0;
  for (int b = 0; b < 2; b++) {
    const Ev *e = b ? two : one;
    int n = b ? 4 : 8;
    memset(buf, 0, sizeof buf);
    for (int i = 0; i < n; i++) {
      buf[i].type = (uint16_t)e[i].type;
      buf[i].code = (uint16_t)e[i].code;
      buf[i].value = e[i].value;
      buf[i].time.tv_sec = e[i].ms / 1000;
      buf[i].time.tv_usec = (e[i].ms % 1000) * 1000;
    }
    if (!writeAll(in[1], buf, (size_t)n * sizeof(input_event))) bad++;
    int r = pump(c);
    if (r != (b ? 0 : 1)) bad++;
    ssize_t rd = read(out[0], got, sizeof got);
    int cnt = rd > 0 ? (int)(rd / (ssize_t)sizeof(input_event)) : 0;
    if (b == 0) {
      if (cnt != 8 || got[2].value != 500 || got[3].value != 1200) bad++;
      if (cnt == 8 && (got[5].value <= 520 || got[6].value <= 1230)) bad++;
    } else {
      if (cnt != 4 || got[0].value != 540 || got[1].type != EV_ABS || got[1].code != ABS_MT_SLOT || got[1].value != 2 ||
          got[2].code != ABS_MT_TRACKING_ID || got[2].value != -1 || got[3].type != EV_SYN || got[3].code != SYN_REPORT) bad++;
    }
  }
  if (gDown != 0 || gDirty != 0) bad++;
  close(in[0]); close(in[1]); close(out[0]); close(out[1]);
  gSource = gUinput = -1;
  printf("%s syn_dropped lifts the fingers and forgets the open frame\n", bad ? "FAIL" : "PASS");
  return bad ? 1 : 0;
}

int main() {
  testCurve();
  testBlend();
  testGain();
  testEuro();
  testRound();
  int n = (int)(sizeof scens / sizeof scens[0]);
  for (int i = 0; i < n; i++) gFails += runScen(scens[i]);
  gFails += testDrop();
  printf(gFails ? "SELFTEST FAIL\n" : "SELFTEST PASS\n");
  return gFails ? 1 : 0;
}
