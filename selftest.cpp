// self test for flick.cpp. it checks the touch sensitivity math against numbers taken from the
// reference implementation: the curve factor, the blend of the two sensitivities, the factor of a
// frame, the one euro filter and whole frames sent through pump. it prints PASS or FAIL per group and
// a last line of SELFTEST PASS or SELFTEST FAIL, the exit code is 0 only on pass.
// the reference is the Magic Touch feature of the Game Corner app by FahrezONE, reverse engineered by
// the project owner, see the origin note in flick.cpp.
// the curve and the filter are plain float math and must match bit for bit. pow may differ by an ulp
// between libms, so blend and factor may be off by two ulp and a scaled position by one raw unit.
// build on a linux host with clang++ -std=c++17 -O2 -ffp-contract=off selftest.cpp -o selftest
// or with the ndk clang the same way, then run the binary from adb shell.
#define main flickMain
#include "flick.cpp"
#undef main

